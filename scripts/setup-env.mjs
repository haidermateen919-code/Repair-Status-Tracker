#!/usr/bin/env node
/**
 * Creates a local `.env` with a strong session secret and a generated owner
 * password. Never overwrites an existing file, and never prints secrets into a
 * tracked file — `.env` is git-ignored.
 *
 * Usage: node scripts/setup-env.mjs
 */
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";

const ENV_PATH = ".env";

if (existsSync(ENV_PATH)) {
  console.log("[setup] .env already exists — leaving it untouched.");
  process.exit(0);
}

const authSecret = randomBytes(32).toString("base64");
const ownerPassword = randomBytes(12).toString("base64url");
const email = "owner@shop.pk";

const contents = `# Generated by scripts/setup-env.mjs on ${new Date().toISOString().slice(0, 10)}.
# Local development only — never commit this file.

AUTH_SECRET=${authSecret}

# Empty DATABASE_URL = embedded Postgres (PGlite) in .data/pglite.
# For production, set this to your Neon/managed Postgres URL, e.g.
# postgresql://user:password@host/dbname?sslmode=require
DATABASE_URL=

SEED_OWNER_EMAIL=${email}
SEED_OWNER_PASSWORD=${ownerPassword}
SEED_OWNER_NAME=Shop Owner

# Change these to the real shop's details before the pilot.
SHOP_NAME=Al-Madina Appliances
SHOP_PHONE=03001234567
SHOP_WHATSAPP=03001234567
SHOP_ADDRESS=Shop 12, Main Bazaar, Islamabad
SHOP_TIMINGS=9am-8pm, Monday closed
`;

writeFileSync(ENV_PATH, contents, { mode: 0o600 });

console.log("[setup] wrote .env");
console.log("");
console.log("  Owner login:  " + email);
console.log("  Password:     " + ownerPassword);
console.log("");
console.log("Keep the password somewhere safe; it is shown only once.");
console.log("Change the SHOP_* values in .env to the real shop's details.");
